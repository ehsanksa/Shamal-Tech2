export type TrainingInterestFormLanguage = keyof typeof trainingInterestFormTranslations

export function getTrainingInterestFormTranslations(lang: TrainingInterestFormLanguage) {
  return trainingInterestFormTranslations[lang]
}

const apiErrorMap: Record<string, keyof (typeof trainingInterestFormTranslations)['en']> = {
  'Full name, mobile, email, and city are required.': 'errorRequiredFields',
  'Please enter a valid email address.': 'errorInvalidEmail',
  'Please select how you are registering.': 'errorRegisteringAs',
  'Please indicate your drone or GIS experience.': 'errorDroneExperience',
  'Please tell us why you are interested in this training.': 'errorTrainingPurpose',
  'Consent is required to submit this form.': 'errorConsent',
  'Invalid referral source.': 'errorInvalidReferral',
  'Failed to submit form. Please try again.': 'submitError',
}

export function translateTrainingInterestApiError(
  message: string | undefined,
  lang: TrainingInterestFormLanguage,
): string {
  const t = getTrainingInterestFormTranslations(lang)
  if (!message) return t.submissionFailed
  const key = apiErrorMap[message]
  return key ? t[key] : message
}
